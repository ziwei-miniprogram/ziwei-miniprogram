// 紫微斗数：由生日推算命宫主星 + 本命宿
function computeZiwei(y, m, d) {
  const idx = ((y + m + d) % ZIWEI_MAIN.length + ZIWEI_MAIN.length) % ZIWEI_MAIN.length;
  const star = ZIWEI_MAIN[idx];
  return {
    star,
    palace: '命宫',
    line: ZIWEI_DESC[star],
    sushe: SUSHE[((y + d) % 28 + 28) % 28]
  };
}

// 八字：简化规则排四柱，统计五行强弱
function computeBazi(y, m, d, h) {
  const yg = TIANGAN[((y - 4) % 10 + 10) % 10] + DIZHI[((y - 4) % 12 + 12) % 12];
  const mg = TIANGAN[(((y * 2 + m) % 10) + 10) % 10] + DIZHI[((m + 2) % 12 + 12) % 12];
  const dg = TIANGAN[((y + m + d) % 10 + 10) % 10] + DIZHI[((y + m + d) % 12 + 12) % 12];
  const hg = TIANGAN[((h + y) % 10 + 10) % 10] + DIZHI[((h % 12) + 12) % 12];
  const chars = [yg[0], yg[1], mg[0], mg[1], dg[0], dg[1], hg[0], hg[1]];
  const cnt = { 金: 0, 木: 0, 水: 0, 火: 0, 土: 0 };
  chars.forEach((c) => { const e = ELMAP[c]; if (e) cnt[e]++; });
  const wx = Object.keys(cnt).map((k) => ({ k, v: cnt[k] }));
  const top = wx.slice().sort((a, b) => b.v - a.v)[0];
  const line = `日主五行偏${top.k}，性格里有${top.k}的韧劲。今日宜顺势而为，先把眼前的小事做漂亮。`;
  return { yg, mg, dg, hg, wx, line };
}

// 星座：随机星级 + 当日文案（娱乐化）
function computeXz(i) {
  const rnd = () => 1 + Math.floor(Math.random() * 5);
  return {
    sign: XZ[i],
    all: rnd(), love: rnd(), career: rnd(), health: rnd(),
    line: XZ_LINE[XZ[i]]
  };
}

